#!/usr/bin/env python3
"""Refresh profile/projects.md from GitHub.

Pulls description, languages, commit count and README summary for the in-scope
repos and writes a fact block per project. The prose under each project is
hand-written in projects.md and preserved across runs -- only the fact table is
regenerated.

The account and its in-scope repositories are personal data, so they come from
the environment (``ROLECALL_GITHUB_OWNER`` and ``ROLECALL_GITHUB_REPOS``, the
latter comma-separated); they are never committed to this repo.

Usage:  python3 sync-github.py [--data <workspace dir>]
"""

import json
import os
import re
import subprocess
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from workspace import data_from_argv, workspace_from_cli  # noqa: E402
from workspaceio import atomic_write  # noqa: E402

OWNER = os.environ.get("ROLECALL_GITHUB_OWNER", "")
REPOS = [repo for repo in os.environ.get("ROLECALL_GITHUB_REPOS", "").split(",") if repo]

# Keep the stored marker stable so existing Profiles retain their hand-written prose.
MARKER = "<!-- SYNCED FACTS -- regenerated by scripts/sync-github.py, do not edit by hand -->"


def gh(*args):
    result = subprocess.run(["gh", *args], capture_output=True, text=True)
    if result.returncode != 0:
        print(f"  ! gh {' '.join(args)}: {result.stderr.strip()}", file=sys.stderr)
        return None
    return result.stdout


class SyncError(Exception):
    pass


def commit_count(repo):
    """Total commits, read from the Link header's last page.

    Raises SyncError on any gh failure -- a wrong 0 in the profile's fact table
    is worse than no update."""
    result = subprocess.run(
        ["gh", "api", "-i", f"repos/{OWNER}/{repo}/commits?per_page=1"],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise SyncError(
            f"commit count for {repo}: {(result.stderr or result.stdout).strip()[:200]}"
        )
    match = re.search(r'page=(\d+)>; rel="last"', result.stdout)
    if match:
        return int(match.group(1))
    if re.search(r"(?m)^\[\s*\{", result.stdout):
        return 1  # one page holding one commit: no "last" link
    raise SyncError(f"commit count for {repo}: could not parse the response")


def fetch(repo):
    meta = gh(
        "repo",
        "view",
        f"{OWNER}/{repo}",
        "--json",
        "description,primaryLanguage,isPrivate,createdAt,pushedAt,homepageUrl,url",
    )
    if meta is None:
        return None
    meta = json.loads(meta)

    langs = gh("api", f"repos/{OWNER}/{repo}/languages")
    langs = json.loads(langs) if langs else {}
    total = sum(langs.values()) or 1
    # Languages above 5% of the codebase, largest first.
    top = [
        key
        for key, value in sorted(langs.items(), key=lambda item: -item[1])
        if value / total >= 0.05
    ]

    return {
        "name": repo,
        "description": (meta.get("description") or "").strip(),
        "private": meta["isPrivate"],
        "url": meta["url"],
        "homepage": (meta.get("homepageUrl") or "").strip(),
        "created": meta["createdAt"][:10],
        "pushed": meta["pushedAt"][:10],
        "languages": top,
        "commits": commit_count(repo),
    }


def render(projects):
    lines = [
        MARKER,
        "",
        f"*Synced {date.today().isoformat()} from github.com/{OWNER}.*",
        "",
        "| Project | Visibility | Stack | Commits | Active | Link |",
        "| :-- | :-- | :-- | --: | :-- | :-- |",
    ]
    for project in projects:
        visibility = "private" if project["private"] else "public"
        link = (
            project["homepage"]
            or (project["url"] if not project["private"] else "—")
        )
        span = (
            project["created"]
            if project["created"] == project["pushed"]
            else f"{project['created']} → {project['pushed']}"
        )
        lines.append(
            f"| {project['name']} | {visibility} | "
            f"{', '.join(project['languages'])} | {project['commits']} | "
            f"{span} | {link} |"
        )
    return "\n".join(lines) + "\n"


def main(argv=None):
    data = workspace_from_cli(data_from_argv(argv))
    out = data / "profile" / "projects.md"
    if not OWNER:
        sys.exit("Set ROLECALL_GITHUB_OWNER to the GitHub account to sync.")
    if not REPOS:
        sys.exit("Set ROLECALL_GITHUB_REPOS to a comma-separated list of repositories.")

    print(f"Syncing {len(REPOS)} repos from github.com/{OWNER} ...")
    projects, failed = [], []
    for repo in REPOS:
        try:
            project = fetch(repo)
        except SyncError as error:
            print(f"  ! {error}", file=sys.stderr)
            project = None
        if project:
            projects.append(project)
        else:
            failed.append(repo)
    if failed:
        sys.exit(
            f"Failed to fetch {', '.join(failed)} -- not touching {out}. "
            "Is `gh auth status` healthy?"
        )

    table = render(projects)

    if out.exists():
        existing = out.read_text()
        if MARKER in existing:
            head, _, tail = existing.partition(MARKER)
            # Keep everything after the synced table's trailing blank line.
            rest = tail.split("\n---\n", 1)
            body = "\n---\n" + rest[1] if len(rest) > 1 else ""
            atomic_write(out, (head + table + body).encode(), 0o600)
            print(f"Updated fact table in {out.relative_to(data)}({len(projects)} projects)")
            return

    out.parent.mkdir(parents=True, exist_ok=True)
    atomic_write(out, f"# Projects\n\n{table}".encode(), 0o600)
    print(f"Wrote {out.relative_to(data)} ({len(projects)} projects)")


if __name__ == "__main__":
    main()
